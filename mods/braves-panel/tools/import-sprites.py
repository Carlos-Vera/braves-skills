#!/usr/bin/env python3
"""Turn a Unicode Mascot Animator export (uma.sujumayas.com) into hooks/sprites.ts.

    python3 tools/import-sprites.py ~/Downloads/animation.json

Keyframes become sprites (named after the keyframe; a repeated name gets -2, -3),
timelines become sequences. The one whose name starts with "work" is the laptop
routine played while Claude works.
"""
import json
import os
import sys

BLANKS = {'', '⠀'}  # the editor's empty cells: nothing, or a braille blank

src = json.load(open(os.path.expanduser(sys.argv[1])))
names, seen = {}, {}
for kid, k in src['keyframes'].items():
    n = k['name']
    seen[n] = seen.get(n, 0) + 1
    names[kid] = n if seen[n] == 1 else f'{n}-{seen[n]}'

palette = []
sprites = {}
for kid, k in src['keyframes'].items():
    rows, ink = [], []
    for row in k['grid']:
        r, i = '', ''
        for cell in row:
            ch = ' ' if cell['char'] in BLANKS else cell['char']
            color = (cell['color'] or k.get('defaultColor')) if ch != ' ' else None
            if color and color not in palette:
                palette.append(color)
            r += ch
            i += str(palette.index(color)) if color else ' '
        rows.append(r)
        ink.append(i)
    sprites[names[kid]] = {'rows': rows, 'ink': ink}

sequences = {}
for s in src['sequences']:
    key = 'work' if s['name'].startswith('work') else s['name']
    sequences[key] = [[names[st['keyframeId']], st['duration']] for st in s['steps'] if st['keyframeId'] in names]

out = os.path.join(os.path.dirname(__file__), '..', 'hooks', 'sprites.ts')
with open(out, 'w') as f:
    f.write('// Generated by tools/import-sprites.py from the Unicode Mascot Animator export. Edit there, not here.\n\n')
    f.write(f'export const PALETTE = {json.dumps(palette)} as const\n\n')
    f.write('/** Each sprite: its rows of characters, and per cell an index into PALETTE (space: no color). */\n')
    f.write('export const SPRITES = {\n')
    for n, sp in sprites.items():
        f.write(f'  {json.dumps(n, ensure_ascii=False)}: {{ rows: {json.dumps(sp["rows"], ensure_ascii=False)}, ink: {json.dumps(sp["ink"])} }},\n')
    f.write('} as const\n\n')
    f.write('export const SEQUENCES = {\n')
    for n, steps in sequences.items():
        f.write(f'  {json.dumps(n)}: {json.dumps(steps)},\n')
    f.write('} as const\n')
print(f'{len(sprites)} sprites, {len(sequences)} sequences, palette {palette} -> {os.path.normpath(out)}')
